# ---------------------------------------------------------------------------
# Determinism gate — run-twice byte/tol-identical (AC-44.2 requirement)
# ---------------------------------------------------------------------------


def test_scorer_parity_run_twice_byte_identical_ac442(
    v3_2_scorer, feature_fixture
) -> None:
    """Two calls to score_pool() over the same inputs produce byte-identical results.

    AC-44.2 requires 'run-twice byte/tol-identical'.  This test verifies that the
    serving path (BlendScorer.score_pool with real v3.2 boosters) is deterministic
    across invocations — a prerequisite for the offline oracle proof to hold.

    Both calls use the same scorer instance (same loaded boosters), the same
    feature fixture.  The result dicts must be exactly equal (Python ==), meaning
    every float64 value is bit-for-bit identical.
    """
    results1 = v3_2_scorer.score_pool(feature_fixture)
    results2 = v3_2_scorer.score_pool(feature_fixture)
    assert results1 == results2, (
        "AC-44.2 determinism gate FAILED: score_pool() over the same inputs "
        "produced different results across two invocations.\n"
        "The serving path must be deterministic for the offline oracle proof to hold."
    )
