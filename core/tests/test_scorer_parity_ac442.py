# Serving path parity gate — the offline oracle proof (AC-44.2 core test)
# ---------------------------------------------------------------------------


def test_scorer_path_reproduces_golden_scores_ac442(
    serving_path_results, golden_df
) -> None:
    """The US-43 serving path reproduces v3.2's golden score vectors.

    This is the 'live==offline by construction' proof for the scorer.

    Inputs:
        Feature fixture: scorer_feature_fixture_ac431.json (5 synthetic tokens)
        Reference pool: built from the pool itself (same as golden generation path)
        Boosters: committed v3.2 boosters (ctrl/oracle/liq × seeds 0–4)

    Tolerance: atol=0.0 (exact / bit-for-bit)
        Justification: LightGBM predict() from a text-format model is deterministic;
        NumPy float64 arithmetic (seed-average, count-rank, mean-of-ranks) is
        deterministic; golden was generated by the same code path + same boosters.
        See module docstring for the full tolerance justification.

    Any deviation from atol=0 indicates a code regression in the serving path or
    corruption of the committed booster files.
    """
    N = len(serving_path_results)
    assert N == len(golden_df), (
        f"Pool size mismatch: serving path returned {N} results, "
        f"golden parquet has {len(golden_df)} rows."
    )

    mismatches = []
    for i, result in enumerate(serving_path_results):
        gold_row = golden_df.iloc[i]
        computed_blend = result["blend_score"]
        golden_blend = float(gold_row["blend_score"])
        if not np.isclose(computed_blend, golden_blend, atol=_ATOL, rtol=_RTOL, equal_nan=False):
            mismatches.append(
                f"token {i}: serving_path={computed_blend:.15f} "
                f"golden={golden_blend:.15f} diff={abs(computed_blend - golden_blend):.2e}"
            )

    assert not mismatches, (
        "AC-44.2 scorer parity gate FAILED — serving path blend_scores do not "
        "match the golden oracle within atol=0.0:\n"
        + "\n".join(mismatches)
        + "\n\nThis is the 'scores in sync' gate: a serving path regression or "
        "booster file corruption has broken live==offline parity by construction."
    )


