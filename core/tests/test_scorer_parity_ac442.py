def test_scorer_path_label_scores_match_golden_ac442(
    serving_path_results, golden_df
) -> None:
    """Per-label seed-averaged predictions match the golden oracle (atol=0).

    label_scores = mean of the 5 seed booster predictions for each label.
    These are the raw floating-point model outputs before percentile-ranking.

    Tolerance: atol=0.0 — same booster text files, same input matrix, same
    numpy mean(), deterministic float64 arithmetic.
    """
    mismatches = []
    for i, result in enumerate(serving_path_results):
        gold_row = golden_df.iloc[i]
        for label in _LABELS:
            col = f"{label}_score"
            computed = result["label_scores"][label]
            golden = float(gold_row[col])
            if not np.isclose(computed, golden, atol=_ATOL, rtol=_RTOL, equal_nan=False):
                mismatches.append(
                    f"token {i} {label}_score: "
                    f"computed={computed:.15f} golden={golden:.15f} "
                    f"diff={abs(computed - golden):.2e}"
                )
    assert not mismatches, (
        "AC-44.2: label_score parity failed (atol=0.0):\n"
        + "\n".join(mismatches)
    )


