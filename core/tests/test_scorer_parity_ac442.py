"""AC-44.2 — Scorer parity gate: the US-43 serving path reproduces v3.2's golden
score vectors within the documented tolerance, given the same feature inputs and
the same reference pool/distribution.

This is the 'live==offline by construction' proof for the scorer — the scorer
analogue of the T0/G1/G2 swap/feature parity gates.

Artefacts
---------
  Banked feature inputs:
      core/tests/fixtures/scorer_feature_fixture_ac431.json
      (5 synthetic tokens; the same fixture used to generate the golden vectors)

  Banked golden score vectors (AC-44.1 offline oracle):
      lake/golden/golden_scores_v3_2/golden_scores.parquet

  Banked v3.2 boosters (committed alongside the golden oracle):
      lake/golden/golden_scores_v3_2/boosters/<label>_s<seed>.txt
      (15 files: ctrl/oracle/liq × seeds 0–4)

  Reference pool/distribution:
      Built from the same 5-token pool via ReferenceDistribution.from_pool_results().
      Using the pool as the reference is identical to the score_pool() computation
      (the parity invariant from AC-43.2 — same inputs + same reference = same ranks).

Tolerance specification
-----------------------
  atol = 0.0  (exact / bit-for-bit reproduction)

  Justification:
    LightGBM booster.predict() loaded from a text-format (.txt) model file is
    fully deterministic across invocations on the same hardware and library
    version — no random state, no numerical variation.  NumPy float64 arithmetic
    (seed-average via mean(), count-based percentile-rank, mean-of-ranks) is
    likewise deterministic.  The golden fixture was generated by the SAME
    BlendScorer.score_pool() code path over the same boosters and the same feature
    fixture.  Re-running the same path therefore produces identical float64 bits.

    An atol=0.0 tolerance is deliberately strict: any deviation from the golden
    vectors indicates either a code regression in the serving path or corruption
    of the committed booster files.

    If the Docker CI environment changes (different numpy/lightgbm ABI) and
    introduces sub-ULP variation, the tolerance should be relaxed to atol=1e-12
    WITH AN EXPLICIT REASON documented here.  Do not relax it pre-emptively.

H1 ImportError trap
-------------------
  Module-level imports of the named gate functions below anchor them by exact
  name.  Deleting or renaming any of them raises ImportError at pytest collection
  time, failing CI BEFORE any tests run (mirroring AC-32.3/AC-36.3).

  AC-44.3 imports these gate functions into the combined T0/G1/G2 suite to
  extend the 'scores in sync' standing Definition-of-Done line.

Tests
-----
Wiring guard (H1 ImportError trap):
  test_scorer_parity_gate_importable_ac442

Booster fixture integrity:
  test_v3_2_boosters_committed_ac442
  test_v3_2_booster_feature_names_match_meta_ac442

Serving path parity gate (core test — the offline oracle proof):
  test_scorer_path_reproduces_golden_scores_ac442

Per-component parity (label scores / ranks / blend):
  test_scorer_path_label_scores_match_golden_ac442
  test_scorer_path_label_ranks_match_golden_ac442
  test_scorer_path_blend_score_match_golden_ac442

Determinism gate:
  test_scorer_parity_run_twice_byte_identical_ac442
"""
