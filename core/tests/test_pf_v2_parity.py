def test_repeat_buyer_frac():
    """Wallet with >= 2 buys counts as repeat buyer."""
    swaps = [
        {"block_time": 100, "slot": 1, "side": "buy", "vol_sol": 1.0,
         "token_amount": 1000, "owner": "AAA", "price": 0.001},
        {"block_time": 110, "slot": 2, "side": "buy", "vol_sol": 1.0,
         "token_amount": 500, "owner": "AAA", "price": 0.002},  # repeat
        {"block_time": 120, "slot": 3, "side": "buy", "vol_sol": 1.0,
         "token_amount": 300, "owner": "BBB", "price": 0.003},
    ]
    result = compute_pf_features(swaps, 200.0)
    assert result is not None
    # 1 of 2 buyers (AAA) is a repeat buyer -> 0.5
    assert abs(result["repeat_buyer_frac"] - 0.5) < 1e-9, (
        f"repeat_buyer_frac={result['repeat_buyer_frac']}"
    )


def test_new_buyers_last60():
    """Only buyers with first buy >= gts-60 count as new_buyers_last60."""
    gts = 1000.0
    swaps = [
        # first buy of AAA at 100 -> not in last 60 (gts-60=940)
        {"block_time": 100, "slot": 1, "side": "buy", "vol_sol": 1.0,
         "token_amount": 1000, "owner": "AAA", "price": 0.001},
        # first buy of BBB at 950 -> in last 60 and last 300
        {"block_time": 950, "slot": 2, "side": "buy", "vol_sol": 1.0,
         "token_amount": 500, "owner": "BBB", "price": 0.002},
        # first buy of CCC at 800 -> in last 300, not last 60
        {"block_time": 800, "slot": 3, "side": "buy", "vol_sol": 1.0,
         "token_amount": 300, "owner": "CCC", "price": 0.003},
    ]
    result = compute_pf_features(swaps, gts)
    assert result is not None
    assert result["new_buyers_last60"] == 1.0, f"new_buyers_last60={result['new_buyers_last60']}"
    assert result["new_buyers_last300"] == 2.0, f"new_buyers_last300={result['new_buyers_last300']}"


def test_price_ret_price_maxrun():
    """price_ret and price_maxrun are computed from price field."""
    gts = 1000.0
    swaps = [
        {"block_time": 100, "slot": 1, "side": "buy", "vol_sol": 1.0,
         "token_amount": 1000, "owner": "AAA", "price": 0.001},  # first_px
        {"block_time": 200, "slot": 2, "side": "buy", "vol_sol": 1.0,
         "token_amount": 500, "owner": "BBB", "price": 0.005},  # max_px
        {"block_time": 300, "slot": 3, "side": "buy", "vol_sol": 1.0,
         "token_amount": 300, "owner": "CCC", "price": 0.003},  # last_px
    ]
    result = compute_pf_features(swaps, gts)
    assert result is not None
    # price_ret = last_px/first_px - 1 = 0.003/0.001 - 1 = 2.0
    assert abs(result["price_ret"] - 2.0) < 1e-9, f"price_ret={result['price_ret']}"
    # price_maxrun = max(px)/first_px - 1 = 0.005/0.001 - 1 = 4.0
    assert abs(result["price_maxrun"] - 4.0) < 1e-9, f"price_maxrun={result['price_maxrun']}"
