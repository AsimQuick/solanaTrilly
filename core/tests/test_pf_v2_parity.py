def test_enrich7_zero_buyers_edge_case():
    """When nbuyers=0 (only sells), all enrich7 features = 0."""
    swaps = [
        {"block_time": 100, "slot": 1, "side": "sell", "vol_sol": 1.0,
         "token_amount": 1000, "owner": "AAA", "price": 0.001},
        {"block_time": 110, "slot": 2, "side": "sell", "vol_sol": 1.0,
         "token_amount": 500, "owner": "BBB", "price": 0.002},
    ]
    # Total sol = 2.0 (from sells), so won't fail total_sol guard
    result = compute_pf_features(swaps, 200.0)
    assert result is not None
    enrich7 = [
        "new_buyers_last60", "new_buyers_last300", "diamond_frac",
        "top5_buyer_share", "repeat_buyer_frac",
    ]
    for fname in enrich7:
        assert result[fname] == 0.0, f"{fname} should be 0 with no buyers, got {result[fname]}"
    # f_value = 0 - 2 = -2 (all sells)
    assert abs(result["f_value"] - (-2.0)) < 1e-9


